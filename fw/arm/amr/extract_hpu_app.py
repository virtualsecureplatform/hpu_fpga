#!/usr/bin/env python3
"""Regenerate amr/hpu_app.c from src/amc.c.

AMR supplies the board management firmware, so only the HPU part of the AVED
derived src/amc.c is linked: the interrupt handlers, the MHDMA worker and the
IOp translation loop. Run this after every upstream change of src/amc.c and
review the diff of hpu_app.c. The script fails if a landmark moved.
"""
from pathlib import Path
import re
import sys

ROOT = Path(__file__).resolve().parent.parent
HEADER = '''/* GENERATED by amr/extract_hpu_app.py from src/amc.c -- do not edit by hand.
 * HPU application; AMD management is supplied by AMR.
 * Original copyright AMD (MIT), HPU additions copyright Zama.
 * No legacy management, GCQ, sensor or flash implementation is linked here. */
#include "FreeRTOS.h"
#include "standard.h"
#include "util.h"
#include "osal.h"
#include "pll.h"
#include "xil_io.h"
#include "xinterrupt_wrap.h"
#include "stream_isc.h"
#include "ucore.h"
#include "ucore_lat.h"
#include "mhdma_driver.h"
#include "hpu_amr.h"
#include <stdbool.h>
#include <stdint.h>
#define AMC_NAME "HPU"
/* Same values as AMC_TASK_PRIOS in src/amc.c. */
#define AMC_TASK_PRIO_DEFAULT 6
#define AMC_TASK_PRIO_HPU_WORKER 7
static void updt_ucore_cfg(UcoreCfg_t *cfg);

'''
RUN_HEAD = '''
void hpu_amr_run(void)
{
    /* Initialize ISR-visible state before any worker or interrupt can run. */
    iop_state_init();
    b2b_pool_init();
    mhdma_table_reset();
    dst_notifyq_init();
    src_store_init();
    dst_store_init();
    for (unsigned int word = 0; word < FW_RUNTIME_MAX_WORD; ++word) {
        ((volatile uint32_t *)DOP_FW_ADDR)[word] = 0;
    }
    HAL_FLUSH_CACHE_DATA((uintptr_t)DOP_FW_ADDR, FW_RUNTIME_MAX_WORD * sizeof(uint32_t));
    /* Initialize queues before publishing readiness to the host. */
    *toAmiIopAckqHead = 0;
    *toAmiIopAckqTail = 0;
    Xil_Out32(HPU_SHARED_BASE + OFFSET_FROM_AMI_IOPQ_HEAD, 0);
    Xil_Out32(HPU_SHARED_BASE + OFFSET_FROM_AMI_IOPQ_TAIL, 0);
    Xil_DCacheFlushRange(HPU_SHARED_BASE + OFFSET_FROM_AMI_IOPQ_HEAD, sizeof(uint32_t));
    Xil_DCacheFlushRange(HPU_SHARED_BASE + OFFSET_FROM_AMI_IOPQ_TAIL, sizeof(uint32_t));
    Xil_DCacheFlushRange((UINTPTR)toAmiIopAckqTail, sizeof(uint32_t));
'''
RUN_TAIL = '''init_failed:
    iOSAL_Interrupt_Disable(XPAR_FABRIC_RTL_INTERRUPT_0_INTR);
    iOSAL_Interrupt_Disable(XPAR_FABRIC_RTL_INTERRUPT_1_INTR);
    iOSAL_Interrupt_Disable(XPAR_FABRIC_RTL_INTERRUPT_3_INTR);
    iOSAL_Interrupt_Disable(XPAR_FABRIC_RTL_INTERRUPT_4_INTR);
    hpu_amr_status(2);
}

'''


def between(lines, start, end, *, include_end=False):
    """Lines from the first one matching `start` up to the next matching `end`."""
    first = [i for i, line in enumerate(lines) if re.search(start, line)]
    if len(first) != 1:
        sys.exit(f'extract_hpu_app: landmark {start!r} found {len(first)} times')
    last = next((i for i in range(first[0] + 1, len(lines)) if re.search(end, lines[i])), None)
    if last is None:
        sys.exit(f'extract_hpu_app: end landmark {end!r} not found after {start!r}')
    return lines[first[0]:last + (1 if include_end else 0)]


def replace_once(text, old, new):
    if text.count(old) != 1:
        sys.exit(f'extract_hpu_app: expected exactly one {old!r}, found {text.count(old)}')
    return text.replace(old, new)


def generate(source):
    lines = source.splitlines(keepends=True)
    types = between(lines, r'^typedef enum \{$', r'^/\*{70,}/$')
    state = between(lines, r'^uint64_t isc_intr_global_cnt', r'^static void vAmcStatusOr')
    buffers = between(lines, r'^/\* IOp/DOp translation buffers \*/', r'^/\*$')
    # Body of vTaskFuncMain after the legacy management initialisation.
    body = between(lines, r'^    // Upon init retrieved ack queue Head and Tail', r'^int main\(')
    while not body[-1].startswith('}'):
        body.pop()          # comment block that precedes main()
    body.pop()              # closing brace of vTaskFuncMain; RUN_TAIL closes instead
    cfg = between(lines, r'^static void updt_ucore_cfg\(UcoreCfg_t\* cfg\)$', r'^}$', include_end=True)

    body = ''.join(body)
    # A failed step leaves the HPU unusable: stop and report it to the host.
    body, count = re.subn(r'(\n +PLL_ERR\( AMC_NAME, "failed [^\n]*\n)', r'\1       goto init_failed;\n', body)
    if count != 10:
        sys.exit(f'extract_hpu_app: expected 10 init failure branches, found {count}')
    # AMR's v80 profile encodes the trigger type in the interrupt id (hpu_profile.h).
    body, count = re.subn(
        r'XSetPriorityTriggerType\( \( XIL_TRIG_LOW_TO_HIGH_EDGE << XINTC_TRIGGER_SHIFT \) \| XPAR_FABRIC_RTL_INTERRUPT_1_INTR,\n'
        r' +HIGH_PRIORITY_INTR,\n +IntrControllerAddr \);',
        'XSetPriorityTriggerType( XPAR_FABRIC_RTL_INTERRUPT_1_INTR, HIGH_PRIORITY_INTR, XPAR_XSCUGIC_0_BASEADDR );', body)
    if count != 1:
        sys.exit('extract_hpu_app: ISC interrupt trigger setup changed')
    body = replace_once(body, 'vAmcStatusOr( HAL_AMC_STATUS_MAIN_RUNNING );', 'hpu_amr_status(1);')

    text = HEADER + ''.join(types) + '\n' + ''.join(state) + ''.join(buffers) + RUN_HEAD + body + RUN_TAIL + ''.join(cfg)
    text = replace_once(text, 'extern uintptr_t IntrControllerAddr;    // GIC base address, exported by the FreeRTOS port\n', '')
    text = text.replace('HAL_RPU_SHARED_MEMORY_BASE_ADDR', 'HPU_SHARED_BASE').replace('FOREVER {', 'for (;;) {')
    for leftover in ('vAmcStatusOr', 'ullAmcInitStatus', 'IntrControllerAddr', 'HAL_AMC_STATUS'):
        if leftover in text:
            sys.exit(f'extract_hpu_app: legacy management reference left: {leftover}')
    return text


if __name__ == '__main__':
    output = ROOT / 'amr/hpu_app.c'
    generated = generate((ROOT / 'src/amc.c').read_text())
    if sys.argv[1:] == ['--check']:
        if output.read_text() != generated:
            sys.exit('amr/hpu_app.c is stale: run fw/arm/amr/extract_hpu_app.py')
    else:
        output.write_text(generated)
